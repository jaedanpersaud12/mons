// Regenerates lib/vendor/htm-preact.ts, lib/vendor/ui-runtime-src.ts and lib/ui-seeds.ts.
// Run `node scripts/build-ui.mjs` after changing anything in ui/ or upgrading htm.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const banner = "// Generated by scripts/build-ui.mjs. Do not edit by hand.\n";
const vendor = readFileSync("node_modules/htm/preact/standalone.umd.js", "utf8");
writeFileSync("lib/vendor/htm-preact.ts", `${banner}export const HTM_PREACT = ${JSON.stringify(vendor)};\n`);

const runtime = readFileSync("ui-runtime/runtime.js", "utf8");
const css = readFileSync("ui-runtime/kit.css", "utf8");
writeFileSync("lib/vendor/ui-runtime-src.ts", `${banner}export const RUNTIME_JS = ${JSON.stringify(runtime)};\nexport const KIT_CSS = ${JSON.stringify(css)};\n`);

const seeds = {};
for (const file of readdirSync("ui").filter((f) => f.endsWith(".js")).sort()) {
  const source = readFileSync(`ui/${file}`, "utf8");
  const title = /^\/\/ title: (.+)$/m.exec(source)?.[1] ?? file;
  seeds[file.replace(/\.js$/, "")] = { title, source };
}
writeFileSync(
  "lib/ui-seeds.ts",
  `${banner}// The first version of each live UI, shipped with the app as v0.\nexport const UI_SEEDS: Record<string, { title: string; source: string }> = ${JSON.stringify(seeds, null, 2)};\n`,
);
console.log("vendor", vendor.length, "seeds", Object.keys(seeds).join(", ") || "(none)");
